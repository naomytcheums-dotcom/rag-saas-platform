"""R-06: retrieval and answer-quality BASELINE of the platform pipeline on a REAL corpus, with real Ollama, against a running local stack.

Corpus: data/processed/fastapi_docs.json (155 pages of the official FastAPI documentation). Questions: data/test_set.json (50 questions with the expected
document, `held_out` flag kept as the evaluation `split`). Configurations compared through the Eval Lab (jobs run by the Celery worker, the answer is
generated by the local model): hybrid (default), vector_only, bm25_only, hybrid_reranked, hybrid + HyDE, hybrid + multi-query.

    python scripts/e2e_retrieval_baseline.py --base http://127.0.0.1:8010 --model qwen2.5:7b --out baseline_fastapi.json

The numbers describe THIS corpus and THIS model on this machine; they are not a general quality claim. Refuses non-local targets.
"""

import argparse
import json
import re
import sys
import time
import uuid
from pathlib import Path

import httpx

ROOT = Path(__file__).resolve().parents[1]
CONFIGS = [
    ("hybrid (default)", {"strategy": "hybrid"}, {"hyde": False, "multi_query": False}),
    ("vector_only", {"strategy": "vector_only"}, {"hyde": False, "multi_query": False}),
    ("bm25_only", {"strategy": "bm25_only"}, {"hyde": False, "multi_query": False}),
    ("hybrid_reranked", {"strategy": "hybrid_reranked"}, {"hyde": False, "multi_query": False}),
    ("hybrid + HyDE", {"strategy": "hybrid"}, {"hyde": True, "multi_query": False}),
    ("hybrid + multi-query", {"strategy": "hybrid"}, {"hyde": False, "multi_query": True}),
]
METRICS = ("recall_at_1", "recall_at_3", "recall_at_5", "mrr", "ndcg_at_5", "faithfulness", "answer_relevance", "context_relevance", "citation_correctness", "hallucination_rate")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", default="http://127.0.0.1:8010")
    ap.add_argument("--model", default="qwen2.5:7b")
    ap.add_argument("--out", default="baseline_fastapi.json")
    ap.add_argument("--limit", type=int, default=0, help="only the first N questions (smoke)")
    ap.add_argument("--configs", default="", help="comma separated indexes of CONFIGS to run (default all)")
    args = ap.parse_args()
    if not re.match(r"^https?://(127\.0\.0\.1|localhost|\[::1\])(:\d+)?$", args.base):
        raise SystemExit("REFUSED: local API only")
    http = httpx.Client(base_url=args.base, timeout=httpx.Timeout(900.0, connect=15.0))

    email, pw = f"baseline-{uuid.uuid4().hex[:8]}@example.com", f"Base-{uuid.uuid4().hex}-Aa1!"
    token = http.post("/auth/register", json={"email": email, "password": pw, "full_name": "Baseline", "accept_terms": True}).json()["access_token"]
    H = {"Authorization": f"Bearer {token}"}
    org = http.post("/organizations", json={"name": f"Baseline {uuid.uuid4().hex[:6]}"}, headers=H).json()["id"]
    http.patch(f"/organizations/{org}/settings", headers=H, json={"llm_provider": "ollama", "llm_model": args.model})

    docs = json.loads((ROOT / "data" / "processed" / "fastapi_docs.json").read_text(encoding="utf-8"))
    questions = json.loads((ROOT / "data" / "test_set.json").read_text(encoding="utf-8"))
    if args.limit:
        questions = questions[: args.limit]
    needed = {p for q in questions for p in q["documents"]}
    ids: dict[str, str] = {}
    started = time.time()
    for d in docs:
        if args.limit and d["path"] not in needed:
            continue
        name = d["path"].replace("/", "__")
        r = http.post(f"/organizations/{org}/documents", headers=H, files={"file": (name, d["content"].encode("utf-8"), "text/markdown")})
        if r.status_code in (200, 201, 202):
            ids[d["path"]] = r.json()["id"]
        else:
            print("upload failed", d["path"], r.status_code, r.text[:100], flush=True)
    print(f"uploaded {len(ids)} documents in {time.time() - started:.0f}s", flush=True)
    pending = set(ids.values())
    deadline = time.time() + 3600
    status_of: dict[str, str] = {}
    while pending and time.time() < deadline:
        items = http.get(f"/organizations/{org}/documents", headers=H, params={"limit": 500}).json()
        items = items if isinstance(items, list) else next((v for v in items.values() if isinstance(v, list)), [])
        for it in items:
            if it["id"] in pending and it["status"] in ("completed", "failed"):
                status_of[it["id"]] = it["status"]
                pending.discard(it["id"])
        time.sleep(10)
    done = sum(1 for s in status_of.values() if s == "completed")
    print(f"processed: {done} completed, {len(status_of) - done} failed, {len(pending)} unfinished, {time.time() - started:.0f}s total", flush=True)

    print("organization", org, flush=True)
    ds = http.post(f"/organizations/{org}/datasets", headers=H, json={"name": "FastAPI docs 50", "description": "data/test_set.json"}).json()["id"]
    added = 0
    for q in questions:
        expected = [{"document_id": ids[p], "relevance_score": 1.0} for p in q["documents"] if p in ids]
        r = http.post(f"/datasets/{ds}/questions", headers=H, json={
            "question": q["question"], "expected_answer": q["answer"], "expected_documents": expected, "difficulty": q.get("difficulty", "easy"),
            "category": q.get("topic"), "split": "held_out" if q.get("held_out") else "tuning"})
        added += r.status_code in (200, 201)
    print(f"questions added: {added}/{len(questions)}", flush=True)

    selected = [int(i) for i in args.configs.split(",") if i] or list(range(len(CONFIGS)))
    results = {}
    for index in selected:
        label, retrieval, flags = CONFIGS[index]
        agent = http.post(f"/organizations/{org}/agents", headers=H, json={
            "name": f"cfg {label}", "system_prompt": "Answer only from the context and cite it.", "model_config": {"provider": "ollama", "model": args.model}})
        agent_id = agent.json()["id"]
        patched = http.patch(f"/agents/{agent_id}/knowledge-base", headers=H, json={"config": {**retrieval, "top_k": 5, **flags}})
        print(f"{label}: agent config {patched.status_code} {'' if patched.status_code < 300 else patched.text[:200]}", flush=True)
        t0 = time.time()
        job = http.post(f"/datasets/{ds}/evaluate", headers=H, json={"agent_id": agent_id}).json().get("id")
        status = None
        while time.time() < t0 + 5400:
            st = http.get(f"/jobs/{job}", headers=H).json()
            status = st.get("status")
            if status in ("completed", "failed", "cancelled"):
                break
            time.sleep(10)
        res = http.get(f"/jobs/{job}/results", headers=H).json()
        res = res if isinstance(res, list) else next((v for v in res.values() if isinstance(v, list)), [])
        agg: dict[str, list[float]] = {m: [] for m in METRICS}
        for item in res:
            metrics = item.get("metrics") or {}
            for m in METRICS:
                if isinstance(metrics.get(m), (int, float)):
                    agg[m].append(float(metrics[m]))
        mean = {m: round(sum(v) / len(v), 3) for m, v in agg.items() if v}
        results[label] = {"job": job, "status": status, "questions": len(res), "seconds": round(time.time() - t0), "means": mean,
                          "retrieval": retrieval, "flags": flags}
        print(f"{label}: {status} {len(res)} results in {time.time() - t0:.0f}s -> {json.dumps(mean)}", flush=True)
        Path(args.out).write_text(json.dumps({"corpus": "FastAPI docs (155 pages)", "documents_indexed": done, "questions": len(questions), "model": args.model,
                                              "results": results, "generated": time.strftime("%Y-%m-%d %H:%M:%S")}, indent=1), encoding="utf-8")
    http.close()
    return 0


if __name__ == "__main__":
    sys.exit(main())
